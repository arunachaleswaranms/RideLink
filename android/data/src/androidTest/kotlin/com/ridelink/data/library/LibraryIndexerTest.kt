package com.ridelink.data.library

import android.net.Uri
import androidx.documentfile.provider.DocumentFile
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.ridelink.core.library.DecodeStatus
import com.ridelink.core.library.LibraryQuery
import com.ridelink.data.database.RideLinkDatabase
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.util.concurrent.atomic.AtomicLong
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * The real pipeline — real Android `ContentResolver`/`MediaMetadataRetriever`/`BitmapFactory`, real
 * SHA-256 file hashing, real Room — against the committed `test-media/synthetic/` fixtures
 * generated by `tools/generate_test_media.py`. This is the end-to-end evidence this phase's brief
 * §26 asks for on the emulator: "indexing... local playback... " starts here with indexing.
 *
 * Fixtures are copied from the test APK's assets (see `data/build.gradle.kts`'s androidTest
 * `assets.directories`) into this app's own private storage before each test, then addressed by a
 * plain `file://` [Uri] — sidestepping SAF/MediaStore permission ceremony entirely, since what is
 * under test here is the indexing *pipeline*, not the picker UI (brief §26's own distinction
 * between what simulator/emulator evidence may and may not claim: real pipeline behaviour, yes;
 * real system picker interaction, no — that remains real-device-gate territory).
 */
@RunWith(AndroidJUnit4::class)
class LibraryIndexerTest {
    private val context = ApplicationProvider.getApplicationContext<android.content.Context>()
    private lateinit var db: RideLinkDatabase
    private lateinit var repository: LibraryRepository
    private lateinit var indexer: LibraryIndexer
    private val clock = AtomicLong(0)

    @Before
    fun setUp() {
        db = Room.inMemoryDatabaseBuilder(context, RideLinkDatabase::class.java).build()
        repository = LibraryRepository(db.trackDao())
        indexer = LibraryIndexer(context, repository, ArtworkCache(context), monotonicNowUs = { clock.incrementAndGet() })
    }

    @After
    fun tearDown() {
        db.close()
    }

    /** Copies a `test-media/synthetic/` asset into this app's private files dir and returns a
     *  `file://` [Uri] for it — a fresh copy per call, so tests never share mutable state through
     *  one file on disk. */
    private fun fixtureUri(assetName: String): Uri {
        val outFile = File(context.filesDir, "fixture-${System.nanoTime()}-$assetName")
        context.assets.open(assetName).use { input -> outFile.outputStream().use { input.copyTo(it) } }
        return Uri.fromFile(outFile)
    }

    @Test
    fun importingANormalTrackExtractsRealMetadataAndArtwork() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("normal.m4a")))
            val entries = repository.observe(LibraryQuery()).first()
            assertEquals(1, entries.size)
            val entry = entries.single()
            assertEquals("Test Track", entry.track.title)
            assertEquals("Test Artist", entry.track.artist)
            assertEquals("Test Album", entry.track.album)
            assertEquals(DecodeStatus.INDEXED, entry.decodeStatus)
            assertTrue(entry.track.durationMs > 0, "a real AAC file must report a real duration")
            assertNotNull(entry.track.artworkRef, "normal.m4a has embedded artwork")
            val artworkFile = ArtworkCache(context).fileFor(entry.track.artworkRef!!)
            assertTrue(artworkFile.exists() && artworkFile.length() > 0, "the cached artwork file must actually exist")
        }

    @Test
    fun missingMetadataFallsBackToFilenameAndUnknownLiterals() =
        runBlocking {
            val uri = fixtureUri("no_metadata.m4a")
            indexer.importFiles(listOf(uri))
            val entry = repository.observe(LibraryQuery()).first().single()
            assertTrue(entry.track.title.startsWith("fixture-"), "falls back to the (fixture-prefixed) filename")
            assertEquals("Unknown Artist", entry.track.artist)
            assertEquals("Unknown Album", entry.track.album)
        }

    @Test
    fun unicodeMetadataRoundTripsThroughRealMediaMetadataRetriever() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("unicode_metadata.m4a")))
            val entry = repository.observe(LibraryQuery()).first().single()
            assertTrue(entry.track.title.contains("楽曲"), "Japanese title text must survive the real platform decoder")
            assertTrue(entry.track.album.contains("專輯"), "Traditional Chinese album text must survive the real platform decoder")
        }

    @Test
    fun noArtworkLeavesArtworkRefNull() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("no_artwork.m4a")))
            val entry = repository.observe(LibraryQuery()).first().single()
            assertNull(entry.track.artworkRef)
        }

    @Test
    fun byteIdenticalDuplicatesDedupToOneLibraryEntry() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("duplicate_a.m4a"), fixtureUri("duplicate_b.m4a")))
            val entries = repository.observe(LibraryQuery()).first()
            assertEquals(1, entries.size, "byte-identical content must dedup to exactly one entry (FR-010)")
        }

    @Test
    fun sameMetadataDifferentContentDoesNotDedup() =
        runBlocking {
            indexer.importFiles(
                listOf(
                    fixtureUri("same_metadata_different_bytes_a.m4a"),
                    fixtureUri("same_metadata_different_bytes_b.m4a"),
                ),
            )
            val entries = repository.observe(LibraryQuery()).first()
            assertEquals(2, entries.size, "identical tags over genuinely different audio must not be deduplicated")
            assertEquals(setOf("Shared Title"), entries.map { it.track.title }.toSet())
        }

    @Test
    fun aTruncatedRealFileIsClassifiedCorruptNotCrashed() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("corrupt.m4a")))
            val entry = repository.observe(LibraryQuery()).first().single()
            assertEquals(DecodeStatus.CORRUPT, entry.decodeStatus)
        }

    @Test
    fun anUnrecognizedExtensionIsClassifiedUnsupportedNeverOpened() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("unsupported.xyz")))
            val entry = repository.observe(LibraryQuery()).first().single()
            assertEquals(DecodeStatus.UNSUPPORTED, entry.decodeStatus)
        }

    @Test
    fun theHandBuiltMp3IsRecognizedByExtensionAndItsId3TagsExtracted() =
        runBlocking {
            // minimal.mp3's audio payload is documented as not a verified decodable fixture (see
            // tools/generate_test_media.py's docstring); this only proves the extension gate lets it
            // through and MediaMetadataRetriever can read its ID3v2 tags without the pipeline
            // crashing, whatever DecodeStatus a given device's decoder ultimately assigns it.
            indexer.importFiles(listOf(fixtureUri("minimal.mp3")))
            val entries = repository.observe(LibraryQuery()).first()
            assertEquals(1, entries.size)
        }

    @Test
    fun importingTheSameFileTwiceUpdatesRatherThanDuplicates() =
        runBlocking {
            val uri = fixtureUri("normal.m4a")
            indexer.importFiles(listOf(uri))
            indexer.importFiles(listOf(uri))
            assertEquals(1, repository.observe(LibraryQuery()).first().size)
        }

    @Test
    fun searchMatchesRealImportedMetadataCaseInsensitively() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("normal.m4a")))
            assertEquals(1, repository.observe(LibraryQuery(searchText = "test track")).first().size)
            assertEquals(1, repository.observe(LibraryQuery(searchText = "TEST ARTIST")).first().size)
            assertEquals(0, repository.observe(LibraryQuery(searchText = "nonexistent")).first().size)
        }

    @Test
    fun aFolderTreeImportSkipsFilesWithUnsupportedExtensionsSilently() =
        runBlocking {
            // A DocumentFile tree (rather than explicit picks) reachable from a plain File directory
            // via DocumentFile.fromFile, proving SafLibraryScanner's recursive walk and its
            // extension gate without needing the system folder picker.
            val root = File(context.filesDir, "tree-${System.nanoTime()}").apply { mkdirs() }
            context.assets.open("normal.m4a").use { input -> File(root, "song.m4a").outputStream().use { input.copyTo(it) } }
            context.assets.open("unsupported.xyz").use { input -> File(root, "notes.xyz").outputStream().use { input.copyTo(it) } }
            val discovered = SafLibraryScanner.scanTree(DocumentFile.fromFile(root))
            assertEquals(listOf("song.m4a"), discovered.map { it.filename })
        }

    @Test
    fun subfolderTraversalFindsNestedTracks() =
        runBlocking {
            val root = File(context.filesDir, "nested-${System.nanoTime()}").apply { mkdirs() }
            val sub = File(root, "subfolder").apply { mkdirs() }
            context.assets.open("normal.m4a").use { input -> File(sub, "nested.m4a").outputStream().use { input.copyTo(it) } }
            val discovered = SafLibraryScanner.scanTree(DocumentFile.fromFile(root))
            assertEquals(listOf("nested.m4a"), discovered.map { it.filename })
        }

    @Test
    fun completeContentHashingFillsInTheLazyHashWithoutChangingIdentity() =
        runBlocking {
            indexer.importFiles(listOf(fixtureUri("normal.m4a")))
            val before = repository.observe(LibraryQuery()).first().single()
            assertNull(before.track.contentHash, "the fast indexing path must not compute the full hash")
            indexer.completeContentHashing(listOf(before))
            val after = repository.observe(LibraryQuery()).first().single()
            assertNotNull(after.track.contentHash)
            assertEquals(before.track.quickId, after.track.quickId, "hashing must not change identity")
        }
}
